#!/usr/bin/env python3
"""Build all binary assets + generated assembler includes into build/."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import palettes as P
import sprites, tiles, levels
from snesgfx import pal_bytes

GAME_TITLE = open(os.path.join(os.path.dirname(__file__), '..', 'TITLE')).read().strip()
OUT = os.path.join(os.path.dirname(__file__), '..', 'build')
os.makedirs(OUT, exist_ok=True)

def w(name, data):
    open(os.path.join(OUT, name), 'wb').write(data)

def main():
    inc = ['; generated by tools/build_assets.py - do not edit', '']

    # ---------------------------------------------------------------- BG1
    mt_chr, entries, attrs, breaks, _ = tiles.build_metatiles()
    w('bg1.chr', mt_chr)
    for name, m in sorted(tiles.MT.items(), key=lambda kv: kv[1]):
        inc.append('MT_%s = %d' % (name, m))
    inc.append('NUM_METATILES = %d' % len(entries))
    for k, v in (('SOLID', tiles.SOLID), ('DESTRUCT', tiles.DESTRUCT), ('PLATFORM', tiles.PLATFORM),
                 ('LADDER', tiles.LADDER), ('HAZARD', tiles.HAZARD), ('DOOR', tiles.DOOR),
                 ('EXIT', tiles.EXIT), ('EMPABLE', tiles.EMPABLE)):
        inc.append('AT_%s = %d' % (k, v))
    inc.append('')
    inc.append('.macro MT_TABLES')
    inc.append('mt_entry: .word ' + ', '.join('$%04X' % e for e in entries))
    inc.append('mt_attr: .byte ' + ', '.join('$%02X' % a for a in attrs))
    inc.append('mt_break: .byte ' + ', '.join('%d' % b for b in breaks))
    inc.append('.endmacro')
    inc.append('')

    # ---------------------------------------------------------------- BG2
    bg2_chr, bg2_map, n2, _ = tiles.build_bg2()
    logo_chr, logo_map, nl = tiles.build_logo(GAME_TITLE, n2)
    bg2_chr += logo_chr
    w('logo.map', b''.join(e.to_bytes(2, 'little') for e in logo_map))
    w('bg2.chr', bg2_chr)
    w('bg2.map', b''.join(e.to_bytes(2, 'little') for e in bg2_map))
    inc.append('BG2_CHR_SIZE = %d' % len(bg2_chr))

    # ---------------------------------------------------------------- font
    w('font.chr', tiles.build_font())

    # ---------------------------------------------------------------- sprites
    sh, tables = sprites.build()
    w('spr.chr', sh.chr_bytes())
    sprites.write_inc(sh, tables, os.path.join(OUT, 'sprites.inc'))

    import sound
    w('spc.bin', sound.build())

    # ---------------------------------------------------------------- palettes
    cg = bytearray(512)
    for i, p in enumerate(P.BG3_PALS):
        cg[i * 8:i * 8 + 8] = pal_bytes(p)
    cg[64:96] = pal_bytes(P.EARTH['surface'])
    cg[96:128] = pal_bytes(P.STONE)
    cg[128:160] = pal_bytes(P.METAL)
    cg[160:192] = pal_bytes(P.CITY)
    cg[192:224] = pal_bytes(P.MISC)
    cg[224:256] = pal_bytes(P.BACK['city'])
    for i, p in enumerate(P.SPR_PALS):
        cg[256 + i * 32:256 + i * 32 + 32] = pal_bytes(p)
    w('palettes.bin', bytes(cg))
    earth_names = list(P.EARTH.keys())
    back_names = list(P.BACK.keys())
    w('earth.bin', b''.join(pal_bytes(P.EARTH[n]) for n in earth_names))
    w('back.bin', b''.join(pal_bytes(P.BACK[n]) for n in back_names))

    # ---------------------------------------------------------------- levels
    for k, v in levels.ET.items():
        inc.append('ET_%s = %d' % (k, v))
    for k, v in levels.OBJ.items():
        inc.append('OBJ_%s = %d' % (k, v))
    lv = ['; generated level data', '']
    mis = []
    for i in range(10):
        L, info = levels.generate(i)
        probs, _n = levels.validate(L, info)
        if probs:
            raise SystemExit('mission %d unreachable targets: %r' % (i + 1, probs))
        w('map%02d.bin' % (i + 1), bytes(v for row in L.t for v in row))
        lv.append('ents_m%d:' % (i + 1))
        assert len(L.ents) <= 100, 'too many entities'
        for (t, p, x, y) in L.ents:
            lv.append('    .byte %d, %d' % (t, p & 255))
            lv.append('    .word %d, %d' % (x, y))
        lv.append('    .byte 0, 0')
        name, earth, back, depth = levels.MISSION_INFO[i]
        sx, sy = info['start']
        ex = info.get('exit') or (0, 0)
        mis.append(dict(start_x=sx * 16 + 8, start_y=(sy + 1) * 16, obj=levels.OBJ[info['obj']],
                        count=info['count'], timer=info.get('timer', 0),
                        surface=info.get('surface', 0) * 16, depth=depth,
                        earth=earth_names.index(earth), back=back_names.index(back),
                        exit_x=ex[0] * 16 + 8, exit_y=ex[1] * 16))
    open(os.path.join(OUT, 'levels_ents.inc'), 'w').write('\n'.join(lv) + '\n')
    lv = ['; generated mission table', '']
    for key in ('start_x', 'start_y', 'obj', 'count', 'timer', 'surface', 'depth', 'earth', 'back', 'exit_x', 'exit_y'):
        lv.append('mis_%s: .word %s' % (key, ', '.join(str(m[key]) for m in mis)))
    lv.append('mis_ents: .faraddr ' + ', '.join('ents_m%d' % (i + 1) for i in range(10)))
    lv.append('    .byte 0')
    open(os.path.join(OUT, 'levels_mis.inc'), 'w').write('\n'.join(lv) + '\n')
    open(os.path.join(OUT, 'defs.inc'), 'w').write('\n'.join(inc) + '\n')
    print('assets ok: bg2 chars %d, sprite blocks %d' % (n2, sh.next_block))

main()
